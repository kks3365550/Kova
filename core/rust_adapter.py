# core/rust_adapter.py
# Python 3.11 compatible, Windows CRLF, pyflakes-clean
"""
Rust Fast Engine Bridge Adapter (kova_fast_engine.exe)
------------------------------------------------------
Enables safe, transactional invocation of the high-performance Rust CAS backup engine.
Features:
1. Auto-discovery of engine_rust/kova_fast_engine.exe binary.
2. VSS snapshot mount isolation: Passes read-only shadow volume paths directly to Rust.
3. Two-Phase Commit (2PC) & Dual-Schema Compatibility:
   Translates Rust SnapshotManifest into standard Python/FastAPI snapshot JSON
   and synchronously registers it with MetadataDB (SQLite) without lock collisions.
4. Non-blocking JSONL progress parsing with CREATE_NO_WINDOW background execution.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import threading
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Sequence

from core.logging_setup import get_logger

log = get_logger("core.rust_adapter")

# Predefined binary names & relative paths
RUST_ENGINE_NAMES = ("kova_fast_engine.exe", "kova_fast_engine")
DEFAULT_SEARCH_PATHS = (
    Path(__file__).resolve().parent.parent / "engine_rust" / "kova_fast_engine.exe",
    Path(__file__).resolve().parent.parent / "engine_rust" / "target" / "release" / "kova_fast_engine.exe",
    Path("engine_rust/kova_fast_engine.exe"),
)


@dataclass(frozen=True)
class RustBackupResult:
    session_id: str
    repo_dir: str
    manifest_path: str
    total_files: int
    total_bytes: int
    dedup_bytes: int
    compressed_bytes: int
    elapsed_seconds: float
    throughput_mb: float
    is_synced_to_sqlite: bool
    raw_summary: Dict[str, Any]


def find_rust_engine_binary() -> Optional[str]:
    """Finds the compiled Rust backup engine executable."""
    # 1. Environment variable override
    env_path = os.environ.get("KOVA_RUST_ENGINE_PATH")
    if env_path and os.path.isfile(env_path) and os.access(env_path, os.X_OK):
        return os.path.abspath(env_path)

    # 2. Well-known candidate locations
    for cand in DEFAULT_SEARCH_PATHS:
        try:
            cand_resolved = cand.resolve()
            if cand_resolved.is_file():
                return str(cand_resolved)
        except Exception:
            pass

    # 3. System PATH lookup
    for name in RUST_ENGINE_NAMES:
        found = shutil.which(name)
        if found:
            return os.path.abspath(found)

    return None


def sync_rust_manifest_to_sqlite(
    repo_dir: str,
    session_id: str,
    profile_name: str = "RustEngine",
    duration_seconds: float = 0.0,
    summary_stats: Optional[Dict[str, Any]] = None
) -> bool:
    """
    Two-Phase Commit Sync:
    Loads snapshots/{session_id}.json generated by Rust engine, adapts it to the standard
    Python snapshot schema (summary, entries, ed25519 signature placeholder),
    and records it into MetadataDB (SQLite) for 100% UI / web API compatibility.
    """
    repo_path = Path(repo_dir).resolve()
    rust_manifest_file = repo_path / "snapshots" / f"{session_id}.json"

    if not rust_manifest_file.is_file():
        log.error(f"[RustAdapter] 매니페스트 파일 누락: {rust_manifest_file}")
        return False

    try:
        with open(rust_manifest_file, "r", encoding="utf-8") as f:
            rust_data = json.load(f)

        # Adapt summary and metadata directly from Rust manifest
        # If standard schema is already present or to avoid duplicate arrays, adapt cleanly
        tot_bytes = rust_data.get("total_bytes", 0)
        ded_bytes = rust_data.get("dedup_bytes", 0)
        cmp_bytes = rust_data.get("compressed_bytes", 0)
        new_stored = max(0, tot_bytes - ded_bytes)
        files_list = rust_data.get("files", [])
        total_count = len(files_list)

        n_files = summary_stats.get("new_files") if summary_stats else None
        m_files = summary_stats.get("modified_files", 0) if summary_stats else 0
        u_files = summary_stats.get("unmodified_files", 0) if summary_stats else 0
        if n_files is None:
            n_files = total_count

        src_root_raw = rust_data.get("source_root", "")
        if isinstance(src_root_raw, str) and ";" in src_root_raw:
            sources_list = [s.strip() for s in src_root_raw.split(";") if s.strip()]
        elif isinstance(src_root_raw, list):
            sources_list = src_root_raw
        elif src_root_raw:
            sources_list = [src_root_raw]
        else:
            sources_list = []

        iso_str = datetime.now(timezone.utc).isoformat()
        standard_manifest = {
            "id": session_id,
            "session_id": session_id,
            "created_at": iso_str,
            "created_at_ts": time.time(),
            "iso_time": iso_str,
            "source_root": src_root_raw if isinstance(src_root_raw, str) else ";".join(sources_list),
            "total_files": total_count,
            "total_bytes": tot_bytes,
            "dedup_bytes": ded_bytes,
            "compressed_bytes": cmp_bytes,
            "files": files_list,
            "profile_id": "rust_fast_engine",
            "profile_name": profile_name,
            "backup_type": "full",
            "base_snapshot_id": None,
            "vss_enabled": True,
            "vss_warnings": [],
            "manifest_signature": None,
            "ed25519_signature": None,
            "encryption": {
                "enabled": False,
                "version": 0,
                "cipher": "none",
                "kdf": {}
            },
            "sources": sources_list,
            "summary": {
                "total_files": total_count,
                "total_bytes": tot_bytes,
                "new_files": n_files,
                "modified_files": m_files,
                "unmodified_files": u_files,
                "deleted_files": 0,
                "new_stored_bytes": new_stored,
                "dedup_saved_bytes": ded_bytes,
                "compressed_bytes": cmp_bytes,
                "duration_seconds": round(duration_seconds, 2)
            },
            "engine": "rust_fast_engine_v1"
        }

        # Atomically overwrite manifest with compact json (never indent=2 for big manifests)
        tmp_target = rust_manifest_file.with_suffix(".tmp_unified")
        with open(tmp_target, "w", encoding="utf-8") as f:
            json.dump(standard_manifest, f, ensure_ascii=False)
        os.replace(tmp_target, rust_manifest_file)

        # Commit to MetadataDB (SQLite)
        from core.metadata_db import MetadataDB
        db = MetadataDB(str(repo_path))
        db.sync_snapshots()
        if new_stored > 0:
            db.record_new_blob(stored_size=new_stored, count=total_count)

        log.info(f"[RustAdapter] SQLite 메타데이터 동기화 완료: {session_id} (파일: {total_count}개)")
        return True

    except Exception as e:
        log.error(f"[RustAdapter] SQLite 동기화 중 오류 ({session_id}): {e}", exc_info=True)
        return False


def run_rust_backup(
    sources: Sequence[str],
    repo_dir: str,
    session_id: Optional[str] = None,
    zstd_level: int = 3,
    progress_callback: Optional[Callable[[Dict[str, Any]], None]] = None,
    cancel_event: Optional[threading.Event] = None,
    vss_mount_map: Optional[Dict[str, str]] = None,
) -> RustBackupResult:
    """
    Executes native Rust backup engine with unbuffered JSON progress streaming,
    Windows CREATE_NO_WINDOW flag, and atomic Two-Phase Commit to MetadataDB.
    """
    binary_path = find_rust_engine_binary()
    if not binary_path:
        raise FileNotFoundError("Rust 백업 엔진 실행 파일(kova_fast_engine.exe)을 찾을 수 없습니다.")

    os.makedirs(repo_dir, exist_ok=True)
    sid = session_id or datetime.now().strftime("%Y%m%d_%H%M%S")

    # Adapt sources if VSS snapshot mounts are provided
    actual_sources: List[str] = []
    for s in sources:
        abs_s = os.path.abspath(s)
        if vss_mount_map and abs_s in vss_mount_map:
            actual_sources.append(vss_mount_map[abs_s])
            log.info(f"[RustAdapter] VSS 스냅샷 경로로 우회 매핑: {abs_s} -> {vss_mount_map[abs_s]}")
        else:
            actual_sources.append(abs_s)

    # Build command line
    cmd = [
        binary_path,
        "backup",
        "--repo", str(Path(repo_dir).resolve()),
        "--session-id", sid,
        "--zstd-level", str(zstd_level),
        "--json"
    ]
    for s in actual_sources:
        cmd.extend(["--source", s])

    # Windows No Window Flag
    creationflags = getattr(subprocess, "CREATE_NO_WINDOW", 0)

    log.info(f"[RustAdapter] Rust 엔진 구동 시작: {sid} (대상 {len(actual_sources)}개)")

    start_t = time.time()
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        creationflags=creationflags
    )

    summary_data: Dict[str, Any] = {}
    last_callback_time = 0.0

    try:
        # Stream JSON lines from stdout
        for line in proc.stdout:
            if cancel_event and cancel_event.is_set():
                log.warning(f"[RustAdapter] 사용자 백업 취소 요청 수신 ({sid}). 프로세스 종료.")
                proc.terminate()
                try:
                    proc.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    proc.kill()
                raise InterruptedError("Rust 백업 작업이 사용자에 의해 취소되었습니다.")

            line = line.strip()
            if not line.startswith("{"):
                continue

            try:
                ev = json.loads(line)
                ev_type = ev.get("type")
                if ev_type == "progress":
                    now = time.time()
                    if progress_callback and (now - last_callback_time >= 0.1):  # 100ms throttle
                        progress_callback(ev)
                        last_callback_time = now
                elif ev_type == "summary":
                    summary_data = ev
            except Exception:
                pass

        stdout_rest, stderr_data = proc.communicate()
        rc = proc.returncode

        if rc != 0:
            err_msg = stderr_data.strip() if stderr_data else f"Exit code {rc}"
            log.error(f"[RustAdapter] Rust 엔진 비정상 종료 (rc={rc}): {err_msg}")
            raise RuntimeError(f"Rust 백업 엔진 오류 (코드 {rc}): {err_msg}")

    except Exception as e:
        if proc.poll() is None:
            proc.kill()
        raise e

    elapsed = time.time() - start_t

    # Step 2: Synchronize with MetadataDB (Two-Phase Commit)
    is_synced = sync_rust_manifest_to_sqlite(repo_dir, sid, duration_seconds=elapsed, summary_stats=summary_data)

    manifest_path = str(Path(repo_dir).resolve() / "snapshots" / f"{sid}.json")

    return RustBackupResult(
        session_id=sid,
        repo_dir=repo_dir,
        manifest_path=manifest_path,
        total_files=summary_data.get("total_files", 0),
        total_bytes=summary_data.get("total_bytes", 0),
        dedup_bytes=summary_data.get("dedup_bytes", 0),
        compressed_bytes=summary_data.get("compressed_bytes", 0),
        elapsed_seconds=elapsed,
        throughput_mb=summary_data.get("throughput_mb", 0.0),
        is_synced_to_sqlite=is_synced,
        raw_summary=summary_data
    )
